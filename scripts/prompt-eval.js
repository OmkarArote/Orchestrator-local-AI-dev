'use strict';
// Prints before/after sizes for a few prompts. No model call and no install. Token counts stay with the chat EWMA.
const { compact } = require('../lib/prompt-compact');

const cases = [
  { name: 'prose', text: 'Hello   \r\n\r\n\r\n\r\nworld\nworld\n\nGenerated by widget\n' },
  { name: 'code', text: 'See:\n```\nconst x = 1;  \nconst x = 1;  \n```\n\n\nthanks\n' },
];
for (const c of cases) {
  const r = compact(c.text, { kind: 'prose' });
  console.log(`${c.name} ${r.before} -> ${r.after}`);
}
