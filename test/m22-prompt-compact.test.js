'use strict';
const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const { compact, bm25 } = require('../lib/prompt-compact');

describe('M13 prompt compact', () => {
  it('is idempotent and keeps a code fence byte-for-byte', () => {
    const src = 'Intro\n\n```\nconst x = 1;  \n```\n\n\nGenerated by acme\n';
    const once = compact(src);
    const twice = compact(once.text);
    assert.equal(twice.text, once.text);
    assert.match(once.text, /```\nconst x = 1;  \n```/);
    assert.equal(once.before, src.length);
    assert.ok(once.after < once.before);
    assert.equal(once.after, 29);
  });

  it('shrinks a long csv and ranks paragraphs with BM25', () => {
    const rows = ['a,b', ...Array.from({ length: 30 }, (_, i) => `${i},${i}`)].join('\n');
    const data = compact(rows, { kind: 'data' });
    assert.ok(data.after < data.before);
    assert.match(data.text, /30 data rows|items=/);
    const chunks = [{ text: 'billing invoice total', provenance: 'a:1' }, { text: 'unrelated gardening notes', provenance: 'b:1' }];
    const picked = bm25(chunks, 'invoice total', 1);
    assert.equal(picked[0].provenance, 'a:1');
  });
});
