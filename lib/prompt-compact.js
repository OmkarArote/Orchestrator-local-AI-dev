'use strict';
// Pure prompt compaction. Idempotent. Code fences are copied through unchanged. Nothing here calls a model.

const FENCE = /```[\s\S]*?```/g;

function splitFences(text) {
  const parts = [];
  let last = 0;
  for (const m of String(text).matchAll(FENCE)) {
    if (m.index > last) parts.push({ code: false, text: text.slice(last, m.index) });
    parts.push({ code: true, text: m[0] });
    last = m.index + m[0].length;
  }
  if (last < text.length) parts.push({ code: false, text: text.slice(last) });
  if (!parts.length) parts.push({ code: false, text: String(text) });
  return parts;
}

function hygieneBlock(text) {
  let s = text.replace(/\r\n/g, '\n').replace(/[\u200b-\u200d\ufeff]/g, '');
  s = s.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n');
  const lines = s.split('\n');
  const out = [];
  for (const line of lines) {
    if (out.length && out[out.length - 1] === line && line.trim()) continue;
    if (/^(?:=|-){8,}$/.test(line) || /^[│┌┐└┘├┤┬┴┼]{4,}$/.test(line)) { out.push(line.slice(0, 8)); continue; }
    out.push(line);
  }
  return out.join('\n').trim();
}

const BOILER = [
  /^#{1,3} (table of contents|contents)$/i,
  /^\[!\[.+\]\(.+\)\]\(.+\)$/,
  /^!\[[^\]]*\]\([^)]+\)$/,
  /^generated by /i,
  /^copyright \(c\)/i,
  /^licensed under /i,
];

function stripBoiler(text) {
  const lines = text.split('\n');
  const kept = lines.filter((line) => !BOILER.some((re) => re.test(line.trim())));
  return kept.join('\n');
}

function shrinkData(text) {
  const t = text.trim();
  if (t.startsWith('{') || t.startsWith('[')) {
    try {
      const j = JSON.parse(t);
      const keys = j && typeof j === 'object' && !Array.isArray(j) ? Object.keys(j).slice(0, 20) : [];
      const n = Array.isArray(j) ? j.length : 1;
      return `JSON ${Array.isArray(j) ? 'array' : 'object'} items=${n}${keys.length ? ` keys=${keys.join(',')}` : ''}`;
    } catch { /* not json */ }
  }
  const rows = t.split('\n').filter((l) => l.includes(',') || l.includes('\t'));
  if (rows.length >= 5 && rows.length > 20) {
    return [rows[0], `# ${rows.length - 1} data rows`, ...rows.slice(1, 6), '…'].join('\n');
  }
  if (/error|exception|warn/i.test(t) && t.split('\n').length > 30) {
    const lines = t.split('\n');
    const sig = new Map();
    for (const line of lines) {
      const k = line.replace(/\d+/g, '#').slice(0, 120);
      if (/error|exception|fail/i.test(line)) sig.set(k, (sig.get(k) || 0) + 1);
    }
    const top = [...sig.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([k, n]) => `${n}x ${k}`);
    return [`log ${lines.length} lines`, ...lines.slice(0, 5), '…', ...lines.slice(-5), ...top].join('\n');
  }
  return text;
}

function tokens(text) {
  return String(text).toLowerCase().match(/[a-z0-9_]{3,}/g) || [];
}

function bm25(chunks, query, k = 4) {
  const docs = chunks.map((c) => tokens(c.text));
  const df = new Map();
  for (const d of docs) for (const w of new Set(d)) df.set(w, (df.get(w) || 0) + 1);
  const q = tokens(query);
  const avg = docs.reduce((a, d) => a + d.length, 0) / (docs.length || 1);
  const scored = chunks.map((c, i) => {
    const tf = new Map();
    for (const w of docs[i]) tf.set(w, (tf.get(w) || 0) + 1);
    let score = 0;
    for (const w of q) {
      const f = tf.get(w) || 0; if (!f) continue;
      const n = df.get(w) || 0;
      const idf = Math.log(1 + (docs.length - n + 0.5) / (n + 0.5));
      score += idf * (f * 2.2) / (f + 1.2 * (0.25 + 0.75 * docs[i].length / (avg || 1)));
    }
    return { ...c, score };
  });
  scored.sort((a, b) => b.score - a.score || a.provenance.localeCompare(b.provenance));
  const picked = [];
  for (const c of scored) {
    if (picked.length >= k) break;
    if (c.score <= 0 && picked.length) continue;
    if (picked.some((p) => p.text === c.text)) continue;
    picked.push(c);
  }
  return picked;
}

function paragraphs(text, provenance) {
  return text.split(/\n{2,}/).map((p, i) => ({ text: p.trim(), provenance: `${provenance}:${i + 1}` })).filter((p) => p.text);
}

/**
 * Compact one string. `query` enables BM25 over paragraphs. Without a query the whole text is kept after hygiene.
 * Returns { text, before, after }.
 */
function compact(input, { query = '', kind = 'prose' } = {}) {
  const original = String(input ?? '');
  const parts = splitFences(original);
  const prose = parts.map((p) => {
    if (p.code) return p.text;
    let s = hygieneBlock(p.text);
    if (kind !== 'code') s = stripBoiler(s);
    if (kind === 'data' || kind === 'log') s = shrinkData(s);
    return s;
  }).filter(Boolean).join('\n\n');
  let text = prose;
  if (query && kind === 'prose') {
    const chosen = bm25(paragraphs(prose, 'p'), query, 6);
    if (chosen.length) text = chosen.map((c) => c.text).join('\n\n');
  }
  if (kind !== 'prose-locked') {
    const again = compact(text, { query: '', kind: 'prose-locked' });
    text = again.text;
  }
  return { text, before: original.length, after: text.length };
}

function charsPerToken(store, fallback = 3.5) {
  const n = Number(store && store.kvGet ? store.kvGet('prompt.chars_per_token') : NaN);
  return Number.isFinite(n) && n > 0.5 && n < 10 ? n : fallback;
}

function notePrompt(store, promptTokens, promptChars) {
  if (!store || !promptTokens || !promptChars) return null;
  const observed = promptChars / promptTokens;
  if (!Number.isFinite(observed) || observed < 0.5 || observed > 10) return null;
  const prev = Number(store.kvGet('prompt.chars_per_token'));
  const next = Number.isFinite(prev) && prev > 0 ? prev * 0.8 + observed * 0.2 : observed;
  const rounded = Math.round(next * 1000) / 1000;
  store.kvSet('prompt.chars_per_token', String(rounded));
  return rounded;
}

module.exports = { compact, bm25, hygieneBlock, charsPerToken, notePrompt };
